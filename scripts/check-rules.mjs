#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const targets = ['src', 'index.html', 'public', 'README.md'];
const violations = [];

function hexToHsl(hex) {
  let c = hex.replace('#', '');
  if (c.length === 3 || c.length === 4) {
    c = c.split('').map((x) => x + x).join('').slice(0, 6);
  } else if (c.length === 8) {
    c = c.slice(0, 6);
  }
  const r = parseInt(c.slice(0, 2), 16) / 255;
  const g = parseInt(c.slice(2, 4), 16) / 255;
  const b = parseInt(c.slice(4, 6), 16) / 255;
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  let h = 0;
  let s = 0;
  const l = (max + min) / 2;

  if (max !== min) {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    switch (max) {
      case r:
        h = (g - b) / d + (g < b ? 6 : 0);
        break;
      case g:
        h = (b - r) / d + 2;
        break;
      case b:
        h = (r - g) / d + 4;
        break;
    }
    h = Math.round(h * 60);
  }
  return { h, s: Math.round(s * 100), l: Math.round(l * 100) };
}

function scanFile(filePath) {
  const relPath = path.relative(rootDir, filePath).replace(/\\/g, '/');
  const isThemeCss = relPath === 'src/index.css';

  const content = fs.readFileSync(filePath, 'utf-8');
  const lines = content.split('\n');

  lines.forEach((line, index) => {
    const lineNum = index + 1;

    // 1. em dash (\u2014) or en dash (\u2013)
    if (/[\u2013\u2014]/.test(line)) {
      violations.push({
        file: relPath,
        line: lineNum,
        rule: 'No em dashes or en dashes',
        detail: line.trim(),
      });
    }

    // 2. emoji (Extended_Pictographic)
    if (/\p{Extended_Pictographic}/u.test(line)) {
      violations.push({
        file: relPath,
        line: lineNum,
        rule: 'No emoji',
        detail: line.trim(),
      });
    }

    // 3. rounded-full, border-radius of 999px or 9999px
    if (/\brounded-full\b|9999?px/i.test(line)) {
      violations.push({
        file: relPath,
        line: lineNum,
        rule: 'No rounded-full or 999px/9999px border-radius',
        detail: line.trim(),
      });
    }

    // 4. bg-gradient, from-, via-, to- utilities, and "gradient" outside theme CSS
    if (!isThemeCss) {
      if (/\bgradient\b/i.test(line)) {
        violations.push({
          file: relPath,
          line: lineNum,
          rule: 'No gradient outside theme CSS file',
          detail: line.trim(),
        });
      }
    }

    // Tailwind gradient utilities
    if (/(?:^|[\s"'`])(?:bg-gradient|from-|via-|to-)/.test(line)) {
      if (/(?:^|[\s"'`])(bg-gradient(?:-[a-z]+)?|(?:from|via|to)-(?:slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose|white|black|transparent|primary|secondary|[a-z0-9]+(?:-\d+)?))(?:[\s"'`]|$)/.test(line)) {
        violations.push({
          file: relPath,
          line: lineNum,
          rule: 'No Tailwind bg-gradient or from-/via-/to- utilities',
          detail: line.trim(),
        });
      }
    }

    // 5. Forbidden words: Antigravity, Claude, Gemini, "Made with", "Built with", "Generated by", "Lorem ipsum", "testimonial"
    const forbiddenWordsRegex = /\b(antigravity|claude|gemini|lorem ipsum|testimonial)\b|made with|built with|generated by/i;
    if (forbiddenWordsRegex.test(line)) {
      violations.push({
        file: relPath,
        line: lineNum,
        rule: 'Forbidden word / AI attribution / placeholder',
        detail: line.trim(),
      });
    }

    // 6. Purple or violet hex colors
    const hexMatches = line.matchAll(/#([0-9a-fA-F]{3,8})\b/g);
    for (const match of hexMatches) {
      const hex = match[0];
      const { h, s, l } = hexToHsl(hex);
      if (s > 15 && l > 5 && l < 95 && h >= 255 && h <= 320) {
        violations.push({
          file: relPath,
          line: lineNum,
          rule: `No purple or violet hex colors (found ${hex}, hue ${h})`,
          detail: line.trim(),
        });
      }
    }

    // 7. <meta name="generator">
    if (/<meta\s+[^>]*name=["']generator["']/i.test(line)) {
      violations.push({
        file: relPath,
        line: lineNum,
        rule: 'No <meta name="generator">',
        detail: line.trim(),
      });
    }
  });
}

function walk(targetPath) {
  if (!fs.existsSync(targetPath)) return;
  const stat = fs.statSync(targetPath);
  if (stat.isFile()) {
    if (!targetPath.includes('.test.')) {
      scanFile(targetPath);
    }
    return;
  }
  const entries = fs.readdirSync(targetPath);
  for (const entry of entries) {
    if (entry === 'node_modules' || entry === 'dist' || entry.includes('.test.')) {
      continue;
    }
    walk(path.join(targetPath, entry));
  }
}

for (const target of targets) {
  walk(path.join(rootDir, target));
}

if (violations.length > 0) {
  console.error(`\x1b[31m[check-rules] Found ${violations.length} rule violation(s):\x1b[0m\n`);
  for (const v of violations) {
    console.error(`  \x1b[33m${v.file}:${v.line}\x1b[0m: [${v.rule}]`);
    console.error(`    ${v.detail}\n`);
  }
  process.exit(1);
} else {
  console.log('\x1b[32m[check-rules] All project rules passed successfully.\x1b[0m');
}
